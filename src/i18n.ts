function leerGuardado(): Idioma {
  try {
    const valor = localStorage.getItem(CLAVE_IDIOMA);
    return valor === "es" || valor === "en" ? valor : "auto";
  } catch {
    return "auto";
  }
}

export function guardarIdioma(idioma: Idioma): void {
  try {
    localStorage.setItem(CLAVE_IDIOMA, idioma);
  } catch {
    // Sin almacenamiento se usa el idioma de Windows.
  }
}

const elegido = leerGuardado();
const enIngles = elegido === "en" || (elegido === "auto" && !navigator.language.toLowerCase().startsWith("es"));

// El texto en español funciona como clave. {0}, {1} son valores que se reemplazan.
export function t(texto: string, ...valores: (string | number)[]): string {
  const base = enIngles ? (INGLES[texto] ?? texto) : texto;
  return base.replace(/\{(\d+)\}/g, (marca, indice: string) => String(valores[Number(indice)] ?? marca));
}

export function traducirPagina(): void {
  for (const atributo of ["title", "aria-label"]) {
    document.querySelectorAll(`[${atributo}]`).forEach((elemento) => {
      elemento.setAttribute(atributo, t(elemento.getAttribute(atributo) ?? ""));
    });
  }
}
